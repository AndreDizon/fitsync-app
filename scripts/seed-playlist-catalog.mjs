import { readFile, writeFile } from 'node:fs/promises'
const file = 'backend/migrations/20261107_plan_playlists.sql'
let sql = await readFile(file, 'utf8')
const refs = []
for (const [kind, filename] of [['workout', 'exercises'], ['nutrition', 'foods']]) {
  const data = JSON.parse(await readFile(`backend/data/${filename === 'foods' ? 'foods-legacy' : filename}.json`, 'utf8'))
  for (const item of data) {
    if (!/^[a-z0-9-]+$/.test(item.id)) throw new Error('Invalid catalog identifier')
    refs.push(`('${kind}', '${item.id}')`)
  }
}
const insert = `-- BEGIN GENERATED CATALOG\ninsert into public.plan_catalog_refs(kind,id) values\n${refs.join(',\n')}\non conflict do nothing;\n-- END GENERATED CATALOG`
sql = sql.includes('-- BEGIN GENERATED CATALOG') ? sql.replace(/-- BEGIN GENERATED CATALOG[\s\S]*?-- END GENERATED CATALOG/, insert) : sql.replace('-- CATALOG_ROWS: generated by scripts/seed-playlist-catalog.mjs', insert)
await writeFile(file, sql)
console.log(`Playlist migration allowlist: ${refs.length} public catalog IDs.`)
const active = JSON.parse(await readFile('backend/data/foods.json', 'utf8'))
for (const food of active) if (!/^[a-z0-9-]+$/.test(food.id)) throw new Error('Invalid food identifier')
await writeFile('backend/migrations/20261128_philippine_food_catalog.sql', `begin;\n\n-- Add the Philippine library IDs without deleting old IDs used by saved records.\n-- No plans, playlists, memberships or user records are changed.\ninsert into public.plan_catalog_refs(kind,id) values\n${active.map(food => `('nutrition', '${food.id}')`).join(',\n')}\non conflict (kind,id) do nothing;\n\ncommit;\n`)
console.log(`Philippine catalog migration: ${active.length} active food IDs; original IDs retained.`)
