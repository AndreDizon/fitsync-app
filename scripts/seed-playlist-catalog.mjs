import { readFile, writeFile } from 'node:fs/promises'
const file = 'backend/migrations/20261107_plan_playlists.sql'
let sql = await readFile(file, 'utf8')
const refs = []
for (const [kind, filename] of [['workout', 'exercises'], ['nutrition', 'foods']]) {
  const data = JSON.parse(await readFile(`backend/data/${filename}.json`, 'utf8'))
  for (const item of data) {
    if (!/^[a-z0-9-]+$/.test(item.id)) throw new Error('Invalid catalog identifier')
    refs.push(`('${kind}', '${item.id}')`)
  }
}
const insert = `-- BEGIN GENERATED CATALOG\ninsert into public.plan_catalog_refs(kind,id) values\n${refs.join(',\n')}\non conflict do nothing;\n-- END GENERATED CATALOG`
sql = sql.includes('-- BEGIN GENERATED CATALOG') ? sql.replace(/-- BEGIN GENERATED CATALOG[\s\S]*?-- END GENERATED CATALOG/, insert) : sql.replace('-- CATALOG_ROWS: generated by scripts/seed-playlist-catalog.mjs', insert)
await writeFile(file, sql)
console.log(`Playlist migration allowlist: ${refs.length} public catalog IDs.`)
