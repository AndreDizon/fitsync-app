import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { build } from 'esbuild'

const source = JSON.parse(await readFile('backend/data/foods-source.json', 'utf8'))
const compiled = await build({ entryPoints: ['frontend/lib/nutrition.ts'], bundle: true, write: false, format: 'esm', platform: 'node' })
const { foods, nutrientsFor, nutritionTotals, foodPreferenceCheck, matchesFoodFilters, foodGroups } = await import(`data:text/javascript;base64,${Buffer.from(compiled.outputFiles[0].text).toString('base64')}`)
assert.equal(foods.length, 100)
assert.equal(new Set(foods.map(food => food.id)).size, 100)
assert.equal(new Set(foods.map(food => food.category)).size, 9)
for (const food of foods) {
  const record = source.records.find(record => Number(record.fdc_id) === food.source.fdcId)
  assert(record, food.id)
  assert.equal(food.nutrients.energyKcal, record.nutrients['1008'])
  const nutrientFields = { energyKcal: '1008', proteinG: '1003', carbsG: '1005', fatG: '1004', fiberG: '1079', sugarsG: '2000', saturatedFatG: '1258', sodiumMg: '1093', calciumMg: '1087', ironMg: '1089', potassiumMg: '1092', vitaminDUg: '1114', vitaminCMg: '1162' }
  for (const [key, sourceId] of Object.entries(nutrientFields)) assert.equal(food.nutrients[key], record.nutrients[sourceId] ?? null, `${food.id}: ${key}`)
  assert(Number.isFinite(food.nutrients.energyKcal) && food.nutrients.energyKcal >= 0, food.id)
  assert(Number.isFinite(food.nutrients.proteinG) && food.nutrients.proteinG >= 0, food.id)
  assert(food.benefits.length >= 2 && food.preparation.length >= 3)
  if (record.portions.length) assert(food.portions.some(portion => portion.source === 'USDA household measure'), food.id + ' source portion')
  else assert.equal(food.defaultPortionId, '100g')
  assert.equal(food.nutrients.proteinG, record.nutrients['1003'])
  assert(food.portions.some(portion => portion.id === food.defaultPortionId))
  for (const values of Object.values(food.classifications)) assert(values.length > 0 && new Set(values).size === values.length)
  assert(food.classifications.groups.every(group => foodGroups.includes(group)))
  for (const portion of food.portions.filter(portion => portion.source === 'USDA household measure')) assert.equal(portion.grams, record.portions.find(item => item.id === portion.id).grams)
  assert.deepEqual(nutrientsFor(food, 100), food.nutrients)
  assert.equal(nutrientsFor(food, 50).energyKcal, food.nutrients.energyKcal / 2)
}
const egg = foods.find(food => food.id === 'hard-boiled-egg')
assert.deepEqual(foodPreferenceCheck(egg, { allergies: ['Eggs'], diet: 'No preference' }).conflicts, ['Eggs'])
assert.equal(foodPreferenceCheck(egg, { allergies: [], diet: 'Vegan' }).matches, false)
const chicken = foods.find(food => food.id === 'roasted-chicken-breast')
assert.equal(foodPreferenceCheck(chicken, { allergies: [], diet: 'Halal' }).needsReview, true)
assert.equal(foodPreferenceCheck(egg, { allergies: ['Other'], diet: 'No preference' }).matches, false)
assert.equal(nutrientsFor({ ...egg, nutrients: { ...egg.nutrients, ironMg: null } }, 50).ironMg, null)
for (const value of [0, -1, 0.5, NaN, Infinity, 2001]) assert.throws(() => nutrientsFor(egg, value))
assert.equal(nutritionTotals([{ foodId: egg.id, grams: 50 }]).energyKcal, 77.5)
const tofu = foods.find(food => food.id === 'calcium-set-tofu')
const filters = { group: 'Legumes', type: 'Soy', preparation: 'Raw', meal: 'Lunch', excludedAllergens: [] }
assert(matchesFoodFilters(tofu, filters))
assert(matchesFoodFilters(tofu, { ...filters, group: 'Protein foods' }))
assert(!matchesFoodFilters(tofu, { ...filters, excludedAllergens: ['Soy'] }))
assert(!matchesFoodFilters(tofu, { ...filters, preparation: 'Roasted' }))
assert(!matchesFoodFilters(tofu, { ...filters, group: 'Fruits' }))
assert(!matchesFoodFilters(tofu, { ...filters, meal: 'Snack' }))
assert.equal(foodPreferenceCheck(foods.find(food => food.id === 'roasted-pork-tenderloin'), { allergies: [], diet: 'Halal' }).matches, false)
for (const group of foodGroups) assert(foods.some(food => food.classifications.groups.includes(group)), group)
console.log('Food library validated: 100 foods, USDA source/portion parity, scaling, missing values, allergy and diet matching.')
