import { createHash } from 'node:crypto'
import { readFile, readdir, writeFile } from 'node:fs/promises'

const folder = new URL('../frontend/public/mascot/optimized/', import.meta.url)
const names = ['fox-greeting', 'hero-fox-head', 'hero-dumbbell', 'hero-apple', 'fox-plan-workout', 'fox-plan-nutrition', 'social-connected-earth', 'fox-social-phone', 'hero-social-phone', 'hero-progress-document', 'fox-logo']
const versions = {}
for (const file of (await readdir(folder)).sort()) {
  if (!names.some(name => file.startsWith(name + '-')) || !file.endsWith('.webp')) continue
  versions[file] = createHash('sha256').update(await readFile(new URL(file, folder))).digest('hex').slice(0, 12)
}
versions['fox-progress.png'] = createHash('sha256').update(await readFile(new URL('../frontend/public/mascot/fox-progress.png', import.meta.url))).digest('hex').slice(0, 12)
const output = new URL('../frontend/lib/hero-asset-versions.ts', import.meta.url)
const contents = '// Generated by scripts/version-hero-assets.mjs. Do not edit manually.\nexport const heroAssetVersions: Record<string, string> = ' + JSON.stringify(versions, null, 2) + '\n'
let previous = ''
try { previous = await readFile(output, 'utf8') } catch {}
if (contents !== previous) await writeFile(output, contents)
console.log(`Versioned ${Object.keys(versions).length} public hero/logo images.`)
