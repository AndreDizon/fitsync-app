import assert from 'node:assert/strict'
import { build } from 'esbuild'
const bundle = await build({ entryPoints: ['shared/progress-journal.ts'], bundle: true, write: false, platform: 'node', format: 'esm' })
const { journalPeriod, journalTrend, journalValue, journalCsv, journalUnit } = await import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].text).toString('base64'))
const entry = (id, date, payload, kind = 'body', created_at = date + 'T10:00:00Z') => ({ id, date, payload, kind, revision: 1, created_at })
const records = [entry('a','2026-11-01',{weightKg:75,bodyFat:20}),entry('b','2026-11-17',{weightKg:76,notes:'Morning log'}),entry('c','2026-11-17',{weightKg:77},'body','2026-11-17T12:00:00Z'),entry('d','2026-11-18',{weightKg:999}),entry('e','2025-01-01',{weightKg:70})]
const period = journalPeriod(records,'2026-11-17',28)
assert.equal(period.length,3)
const trend = journalTrend(period,'weightKg')
assert.equal(trend.latest.value,77)
assert.equal(trend.points.length,2,'Multiple same-day measurements produce one chart point')
assert.equal(trend.change,2)
assert.equal(journalTrend([records[0]],'weightKg').change,null)
assert.equal(journalTrend([],'weightKg').latest,undefined)
assert.equal(journalValue(records[0],'fatMass'),15)
assert.equal(journalValue(records[1],'fatMass'),null,'Never combine body fat and weight from different entries')
assert.equal(journalValue(entry('f','2026-11-17',{sleepHours:0},'wellness'),'sleepHours'),0,'Zero is a logged value, not missing')
assert.equal(journalPeriod(records,'2026-11-17',0).length,4,'All loaded history still excludes future records')
assert.equal(journalUnit('waist'),'cm')
const csv = journalCsv([entry('g','2026-11-17',{weightKg:72,notes:'=HYPERLINK("test")'}),entry('h','2026-11-17',{path:'secret/photo'},'photo')])
assert(csv.includes("'=HYPERLINK"),'Prevent spreadsheet formulas in notes')
assert(!csv.includes('secret/photo'))
assert(csv.includes('"Weight","72","kg"'))
assert.equal(csv.split('\r\n').length,2)
console.log('PASS journal: date ranges, same-day logs, measurement changes, paired composition, zero values and safe CSV export')
